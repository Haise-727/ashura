#!/usr/bin/env bash
# Ashura installer: puts this repo's rice into your existing home.
#
# It never creates a user or a login session: you keep logging in as yourself,
# with the same "Hyprland" entry. Everything it replaces is first MOVED into
#   ~/.local/state/ashura/backup-<time>/
# next to a generated rollback.sh that puts it all back.
#
# Left alone on purpose: your fish config.fish, kitty.conf, your terminal, editor
# and prompt configs, an existing fuzzel.ini or monitors.lua, and the login screen
# (change that later with /logintheme in search).
#
# Usage:
#   ashura/install.sh              install (asks for sudo for packages)
#   ashura/install.sh --dry-run    print what would happen, change nothing
#   ashura/install.sh --no-packages --home DIR
#                                  rehearse the file steps on another folder
set -euo pipefail

REPO="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
DOTS="$REPO/dots"
TARGET="$HOME"
DRY=0
PACKAGES=1
FONTS=1
VENV=1

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run) DRY=1 ;;
        --no-packages) PACKAGES=0 ;;
        --no-fonts) FONTS=0 ;;
        --no-venv) VENV=0 ;;
        --home) TARGET="$(readlink -f "$2")"; shift ;;
        -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP="$TARGET/.local/state/ashura/backup-$STAMP"
ROLLBACK="$BACKUP/rollback.sh"

say()  { printf '\033[1m==>\033[0m %s\n' "$*"; }
note() { printf '    %s\n' "$*"; }
run()  { if [ "$DRY" = 1 ]; then note "[dry-run] $*"; else "$@"; fi; }

# Packages the shell and its features use. All from the official repos.
PKGS=(
    qt6-positioning kirigami syntax-highlighting   # QML modules the shell imports
    translate-shell                                 # left sidebar translator
    hyprlock                                        # lock guard's fallback locker
    libqalculate                                    # math in search
    tesseract tesseract-data-eng                    # OCR screenshot bind
    hyprsunset                                      # night light toggle
    pavucontrol-qt                                  # volume mixer app
    songrec                                         # music recognition button
    nautilus kdialog                                # file manager, dialogs
    bc ripgrep rsync wget xdg-user-dirs go-yq eza jq
    adw-gtk-theme                                   # GTK theme the palette recolours
    uv                                              # builds the colour venv
    gnome-system-monitor                            # Ctrl+Shift+Esc, task manager button
    blueman nm-connection-editor                    # Bluetooth and network buttons
    mpv-mpris                                       # lofi stream in the player card
    qt6ct                                           # Qt apps take the palette through it
    fuzzel                                          # launcher when the shell is not running
)

# ----------------------------------------------------------------- preflight
[ "$(id -u)" -ne 0 ] || { echo "run as your user, not root" >&2; exit 1; }
[ -d "$DOTS/.config/hypr" ] || { echo "no dots/ next to this script ($DOTS)" >&2; exit 1; }
[ -f "$DOTS/.config/quickshell/ashura/modules/common/widgets/shapes/material-shapes.js" ] || {
    echo "the shapes submodule is missing: run 'git submodule update --init' in $REPO" >&2; exit 1; }
command -v qs >/dev/null || { echo "quickshell (qs) is not installed" >&2; exit 1; }
say "Ashura from $REPO"
note "into $TARGET   (backup: $BACKUP)"
[ "$DRY" = 1 ] && note "DRY RUN: nothing will be changed"

# ----------------------------------------------------------------- backup helpers
# Every replaced path is moved (not copied) into the backup, and a line that
# restores it is added to rollback.sh, so rolling back is exact.
init_backup() {
    run mkdir -p "$BACKUP"
    if [ "$DRY" = 0 ]; then
        cat > "$ROLLBACK" <<EOF
#!/usr/bin/env bash
# Generated by Ashura's installer on $STAMP. Puts back everything it replaced
# and removes what it added. Then log out and back in.
set -u
B="$BACKUP"
T="$TARGET"
EOF
        # Quoted heredoc: these lines are evaluated when the rollback RUNS.
        cat >> "$ROLLBACK" <<'EOF'
[ -e "$B/ROLLED-BACK" ] && { echo "already rolled back: $B"; exit 0; }
# Newer installs must be rolled back first (they backed up THIS install's files).
for other in "$T"/.local/state/ashura/backup-*; do
    if [[ "$other" > "$B" ]] && [ ! -e "$other/ROLLED-BACK" ]; then
        echo "roll back the newer install first: $other/rollback.sh"; exit 1
    fi
done
EOF
        chmod +x "$ROLLBACK"
    fi
}
# replace <relative path>: move the current one aside (if any) and record how to undo.
replace() {
    local rel="$1"
    if [ -e "$TARGET/$rel" ] || [ -L "$TARGET/$rel" ]; then
        run mkdir -p "$(dirname "$BACKUP/files/$rel")"
        run mv "$TARGET/$rel" "$BACKUP/files/$rel"
        # Guarded: only acts while the backup copy is still there, so running the
        # rollback twice can never delete what the first run restored.
        [ "$DRY" = 1 ] || printf 'if [ -e "$B/files/%s" ] || [ -L "$B/files/%s" ]; then rm -rf "$T/%s"; mkdir -p "$(dirname "$T/%s")"; mv "$B/files/%s" "$T/%s"; fi\n' "$rel" "$rel" "$rel" "$rel" "$rel" "$rel" >> "$ROLLBACK"
    else
        [ "$DRY" = 1 ] || printf 'rm -rf "$T/%s"\n' "$rel" >> "$ROLLBACK"
    fi
}
install_dir() {   # install_dir <relative path>: replace it with the repo's copy
    replace "$1"
    run mkdir -p "$(dirname "$TARGET/$1")"
    run cp -a "$DOTS/$1" "$TARGET/$1"
}
install_if_missing() {   # keep the user's file when there is one
    if [ -e "$TARGET/$1" ]; then
        note "kept your $1"
    else
        [ "$DRY" = 1 ] || printf 'rm -f "$T/%s"\n' "$1" >> "$ROLLBACK"
        run mkdir -p "$(dirname "$TARGET/$1")"
        run cp -a "$DOTS/$1" "$TARGET/$1"
    fi
}

# ----------------------------------------------------------------- 1. packages
if [ "$PACKAGES" = 1 ]; then
    say "Packages (sudo will ask for your password)"
    missing=()
    for p in "${PKGS[@]}"; do pacman -Q "$p" >/dev/null 2>&1 || missing+=("$p"); done
    if [ ${#missing[@]} -eq 0 ]; then
        note "all present"
    else
        note "installing: ${missing[*]}"
        run sudo pacman -S --needed "${missing[@]}"
    fi
    # The cursor (Bibata Modern Classic) is in the AUR, not the official repos:
    # build bibata-cursor-theme-bin from its AUR recipe.
    if ! pacman -Q bibata-cursor-theme-bin >/dev/null 2>&1 \
        && ! [ -d /usr/share/icons/Bibata-Modern-Classic ]; then
        note "building the Bibata cursor package (AUR bibata-cursor-theme-bin)"
        if [ "$DRY" = 1 ]; then
            note "[dry-run] git clone the AUR recipe + makepkg -si"
        else
            cdir=$(mktemp -d)
            (git clone -q https://aur.archlinux.org/bibata-cursor-theme-bin.git "$cdir/pkg" \
                && cd "$cdir/pkg" && makepkg -si --noconfirm >/dev/null) \
                || note "cursor package failed; the default cursor shows instead"
            rm -rf "$cdir"
        fi
    fi
fi

# 144 fps in the Balanced power profile: keep the CPU's energy preference on
# "performance" outside the power saver (ashura/system/ashura-epp).
if [ "$PACKAGES" = 1 ] && ! systemctl is-enabled ashura-epp.service >/dev/null 2>&1; then
    say "CPU energy preference service (144 fps in Balanced)"
    run sudo install -m 755 "$REPO/ashura/system/ashura-epp" /usr/local/bin/ashura-epp
    run sudo install -m 644 "$REPO/ashura/system/ashura-epp.service" /etc/systemd/system/ashura-epp.service
    run sudo systemctl daemon-reload
    run sudo systemctl enable --now ashura-epp.service
fi

earlier=$(ls -d "$TARGET"/.local/state/ashura/backup-* 2>/dev/null | head -1 || true)
if [ -n "$earlier" ]; then
    note "an earlier install's backup exists: $earlier"
    note "your ORIGINAL files are there; this run's backup will hold the current Ashura files"
fi
init_backup

# ----------------------------------------------------------------- 2. configs
say "Configs"
for rel in .config/hypr .config/quickshell/ashura .config/matugen .config/xdg-desktop-portal .config/wlogout; do
    note "$rel"
    install_dir "$rel"
done
# Your screens. Not shipped in the repo because it is per machine; sync.sh never
# touches it. An existing monitors.lua is carried over from the backup; without
# one, every screen runs at its highest refresh rate. Edit it for your layout.
if [ "$DRY" = 0 ] && [ -f "$BACKUP/files/.config/hypr/monitors.lua" ]; then
    cp -a "$BACKUP/files/.config/hypr/monitors.lua" "$TARGET/.config/hypr/monitors.lua"
    note ".config/hypr/monitors.lua (yours, kept)"
elif [ "$DRY" = 0 ] && [ ! -e "$TARGET/.config/hypr/monitors.lua" ]; then
    cat > "$TARGET/.config/hypr/monitors.lua" <<'EOF'
-- Your screens (written once by Ashura's installer; edit freely).
-- Example: hl.monitor({ output = "eDP-1", mode = "1920x1080@144", position = "0x0", scale = 1 })
hl.monitor({ output = "", mode = "highrr", position = "auto", scale = 1 })
EOF
fi
for rel in .config/ashura/config.json .config/ashura/booru-blacklist.txt .config/ashura/booru-keys.json.example .config/fuzzel/fuzzel.ini; do
    install_if_missing "$rel"
done

# kitty: colors.conf points at the theme the shell generates from the wallpaper.
# Your kitty.conf needs `include colors.conf` for it to apply.
if [ -f "$TARGET/.config/kitty/kitty.conf" ]; then
    note ".config/kitty/colors.conf -> the shell's generated theme"
    replace .config/kitty/colors.conf
    [ "$DRY" = 1 ] || printf '# Ashura: colours from the shell (wallpaper palette).\ninclude ~/.local/state/quickshell/user/generated/terminal/kitty-theme.conf\n' > "$TARGET/.config/kitty/colors.conf"
    grep -q '^include colors.conf' "$TARGET/.config/kitty/kitty.conf" \
        || note "add 'include colors.conf' to your kitty.conf for wallpaper colours"
fi
# GTK: matugen rewrites these two files on every wallpaper change. Back up what
# is there now (another theme tool's colours, say) so a rollback is exact.
for rel in .config/gtk-3.0/gtk.css .config/gtk-4.0/gtk.css; do
    if [ -e "$TARGET/$rel" ]; then note "$rel (regenerated from your wallpaper)"; replace "$rel"; fi
done
# Qt: qt6ct reads its colour scheme from color_scheme_path. Matugen writes
# ~/.config/qt6ct/colors/ashura.conf from the wallpaper; point qt6ct at it and
# keep everything else in your qt6ct.conf (icons, fonts, style) as it was.
if [ -f "$TARGET/.config/qt6ct/qt6ct.conf" ]; then
    note ".config/qt6ct/qt6ct.conf -> wallpaper colour scheme"
    replace .config/qt6ct/qt6ct.conf
    if [ "$DRY" = 0 ]; then
        sed -e "s|^color_scheme_path=.*|color_scheme_path=$TARGET/.config/qt6ct/colors/ashura.conf|" \
            -e 's|^custom_palette=.*|custom_palette=true|' \
            "$BACKUP/files/.config/qt6ct/qt6ct.conf" > "$TARGET/.config/qt6ct/qt6ct.conf"
        # if those keys were missing, add them under [Appearance]
        f="$TARGET/.config/qt6ct/qt6ct.conf"
        grep -q '^\[Appearance\]' "$f" || printf '[Appearance]\n' >> "$f"
        grep -q '^color_scheme_path=' "$f" || sed -i "/^\[Appearance\]/a color_scheme_path=$TARGET/.config/qt6ct/colors/ashura.conf" "$f"
        grep -q '^custom_palette=' "$f" || sed -i '/^\[Appearance\]/a custom_palette=true' "$f"
    fi
fi
# fish: an extra conf.d file; your config.fish is untouched.
if [ -d "$TARGET/.config/fish" ]; then
    note ".config/fish/conf.d/ashura-colors.fish"
    replace .config/fish/conf.d/ashura-colors.fish
    if [ "$DRY" = 0 ]; then
        mkdir -p "$TARGET/.config/fish/conf.d"
        cat > "$TARGET/.config/fish/conf.d/ashura-colors.fish" <<'EOF'
# Ashura: apply the shell's terminal palette to new terminals.
if status is-interactive; and test -f ~/.local/state/quickshell/user/generated/terminal/sequences.txt
    cat ~/.local/state/quickshell/user/generated/terminal/sequences.txt
end
EOF
    fi
fi

# Live wallpapers: the picker's Live mode opens ~/Pictures/Wallpapers/Live. It
# gets an entry (<name>.ashura) for each shader wallpaper, which are the shaders
# that ship a preview image; the others are effects, not wallpapers. Put videos
# (or folders of them) in the same folder.
LIVE="$TARGET/Pictures/Wallpapers/Live"
if [ ! -e "$LIVE" ]; then
    note "Pictures/Wallpapers/Live (shader wallpapers; add your videos there)"
    [ "$DRY" = 1 ] || printf 'rm -rf "$T/Pictures/Wallpapers/Live"\n' >> "$ROLLBACK"
    run mkdir -p "$LIVE"
    for f in "$DOTS"/.config/quickshell/ashura/assets/ashura/shaders/*.frag.qsb; do
        n=$(basename "$f" .frag.qsb)
        [ -f "${f%.frag.qsb}.png" ] || continue
        [ "$DRY" = 1 ] || echo "$n" > "$LIVE/$n.ashura"
    done
fi

# ----------------------------------------------------------------- 3. fonts
if [ "$FONTS" = 1 ]; then
    say "Fonts (into ~/.local/share/fonts/ashura)"
    F="$TARGET/.local/share/fonts/ashura"
    if [ -d "$F" ]; then
        note "already there"
    else
        [ "$DRY" = 1 ] || printf 'rm -rf "$T/.local/share/fonts/ashura"\n' >> "$ROLLBACK"
        run mkdir -p "$F"
        run git clone -q --depth 1 https://github.com/end-4/google-sans-flex "$F/google-sans-flex"
        for u in \
            "https://github.com/google/material-design-icons/raw/master/variablefont/MaterialSymbolsRounded%5BFILL,GRAD,opsz,wght%5D.ttf" \
            "https://github.com/google/fonts/raw/main/ofl/readexpro/ReadexPro%5BHEXP,wght%5D.ttf" \
            "https://github.com/google/fonts/raw/main/ofl/spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf"; do
            run curl -fsSL -o "$F/$(basename "$u" | sed 's/%5B/[/g; s/%5D/]/g')" "$u"
        done
        run fc-cache -f
    fi
fi

# ----------------------------------------------------------------- 4. colour venv
if [ "$VENV" = 1 ]; then
    say "Colour generator venv"
    V="$TARGET/.local/state/quickshell/.venv"
    if [ -x "$V/bin/python" ] && "$V/bin/python" -c 'import PIL, materialyoucolor' 2>/dev/null; then
        note "already there"
    else
        [ "$DRY" = 1 ] || printf 'rm -rf "$T/.local/state/quickshell/.venv"\n' >> "$ROLLBACK"
        run uv venv -q "$V"
        # materialyoucolor is pinned: newer releases renamed keys the colour script reads.
        run env VIRTUAL_ENV="$V" uv pip install -q pillow numpy "materialyoucolor==2.0.10"
    fi
fi

# ----------------------------------------------------------------- 5. login screen picker
say "Login screen themes (qylock) and the picker's root helper"
Q="$TARGET/.local/share/ashura/qylock"
if [ -d "$Q/themes" ]; then
    note "qylock already in ~/.local/share/ashura/qylock"
else
    [ "$DRY" = 1 ] || printf 'rm -rf "$T/.local/share/ashura/qylock"\n' >> "$ROLLBACK"
    run mkdir -p "$(dirname "$Q")"
    run git clone -q --depth 1 https://github.com/Darkkal44/qylock "$Q"
fi
if [ "$PACKAGES" = 1 ]; then
    # Root-owned so pkexec runs a file only root can change. Not undone by
    # rollback.sh (it is harmless and needs sudo to remove).
    run sudo install -m 755 -o root -g root "$REPO/ashura/sddm/ashura-sddm-theme" /usr/local/bin/ashura-sddm-theme
fi

# ----------------------------------------------------------------- 6. devpit
# The cockpits call `devpit`. When none is on PATH, link the copy in the devpit/
# submodule (clone with --recursive, or run `git submodule update --init`).
if ! command -v devpit >/dev/null 2>&1 && [ ! -e "$TARGET/.local/bin/devpit" ]; then
    if [ -x "$REPO/devpit/bin/devpit" ]; then
        say "devpit on PATH (from the devpit/ submodule)"
        [ "$DRY" = 1 ] || printf 'rm -f "$T/.local/bin/devpit"\n' >> "$ROLLBACK"
        run mkdir -p "$TARGET/.local/bin"
        run ln -s "$REPO/devpit/bin/devpit" "$TARGET/.local/bin/devpit"
    else
        note "devpit not found: run 'git submodule update --init' for the cockpits"
    fi
fi

# ----------------------------------------------------------------- done
if [ "$DRY" = 0 ]; then
    # Folders the install created, removed only if nothing else ended up in them.
    for d in .config/quickshell .config/ashura .local/share/fonts .local/share/ashura .local/state/quickshell .local/bin Pictures/Wallpapers Pictures; do
        printf 'rmdir --ignore-fail-on-non-empty "$T/%s" 2>/dev/null\n' "$d" >> "$ROLLBACK"
    done
    printf 'touch "$B/ROLLED-BACK"\necho "Ashura rolled back from %s. Log out and back in."\n' "$BACKUP" >> "$ROLLBACK"
fi
say "Done."
note "Backup and rollback: $ROLLBACK"
[ -n "$earlier" ] && note "To get back to your original setup: run each rollback.sh, newest first (it refuses the wrong order)."
note "Save your work, then log out and back in (same 'Hyprland' entry)."
note "First login: pick a wallpaper with Ctrl+Super+T or Super+W to set the colours."
